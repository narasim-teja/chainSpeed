/**
 * Writes the compiled SpeedRegistry and XPRewards ABIs into the app, so the app's ABI can never
 * drift from the contract. Run after `bunx hardhat compile`:
 *
 *   bun scripts/export-abi.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

for (const [contract, constName, file] of [
  ["SpeedRegistry", "SPEED_REGISTRY_ABI", "SpeedRegistryAbi.ts"],
  ["XPRewards", "XP_REWARDS_ABI", "XPRewardsAbi.ts"],
]) {
  const artifact = JSON.parse(
    readFileSync(join(import.meta.dir, "..", "artifacts", "contracts", `${contract}.sol`, `${contract}.json`), "utf8")
  );
  const out = join(import.meta.dir, "..", "..", "constants", file);
  writeFileSync(
    out,
    `// Generated by contracts/scripts/export-abi.ts from the compiled contract. Do not edit by hand.\n` +
      `export const ${constName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
  );
  console.log(`Wrote ${artifact.abi.length} ABI entries to ${out}`);
}
