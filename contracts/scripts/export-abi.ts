/**
 * Writes the compiled SpeedRegistry ABI into the app, so the app's ABI can never
 * drift from the contract. Run after `bunx hardhat compile`:
 *
 *   bun scripts/export-abi.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const artifact = JSON.parse(
  readFileSync(join(import.meta.dir, "..", "artifacts", "contracts", "SpeedRegistry.sol", "SpeedRegistry.json"), "utf8")
);

const out = join(import.meta.dir, "..", "..", "constants", "SpeedRegistryAbi.ts");
writeFileSync(
  out,
  `// Generated by contracts/scripts/export-abi.ts from the compiled contract. Do not edit by hand.\n` +
    `export const SPEED_REGISTRY_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
);
console.log(`Wrote ${artifact.abi.length} ABI entries to ${out}`);
